/**
 * Regenerates `src/components/world-map-data.ts` — the dotted world map behind
 * the landing hero.
 *
 * Samples land on a fixed graticule and emits one cell per land point, so the
 * continents are drawn with the same mark as the wordmark's `o`.
 *
 * Usage:
 *   curl -sSL -o /tmp/land.geojson \
 *     https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson
 *   node scripts/generate-world-map.mjs /tmp/land.geojson
 *
 * Source geometry: Natural Earth 110m land, public domain.
 */
import fs from "node:fs";
import path from "node:path";

const STEP = 3; // degrees between samples
// Antarctica and the high Arctic are cropped: on an equirectangular grid they
// oversample into solid bars across the edges rather than reading as land.
const LAT_MAX = 72;
const LAT_MIN = -56;

const input = process.argv[2];
if (!input) {
  console.error("usage: node scripts/generate-world-map.mjs <land.geojson>");
  process.exit(1);
}

const geo = JSON.parse(fs.readFileSync(input, "utf8"));

/**
 * Ray casting against a single ring. Outer rings and holes are both tested and
 * both flip the parity, so lakes — and islands inside them — come out right.
 */
function inRing(lon, lat, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (
      yi > lat !== yj > lat &&
      lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi
    ) {
      inside = !inside;
    }
  }
  return inside;
}

// Precomputed bounding boxes keep the full scan (thousands of samples against
// ~130 rings) fast enough to be instant.
const rings = geo.features
  .flatMap((f) => f.geometry.coordinates)
  .map((ring) => {
    let minX = 180;
    let maxX = -180;
    let minY = 90;
    let maxY = -90;
    for (const [x, y] of ring) {
      if (x < minX) minX = x;
      if (x > maxX) maxX = x;
      if (y < minY) minY = y;
      if (y > maxY) maxY = y;
    }
    return { ring, minX, maxX, minY, maxY };
  });

function isLand(lon, lat) {
  let inside = false;
  for (const b of rings) {
    if (lon < b.minX || lon > b.maxX || lat < b.minY || lat > b.maxY) continue;
    if (inRing(lon, lat, b.ring)) inside = !inside;
  }
  return inside;
}

const cols = Math.round(360 / STEP);
const rows = Math.round((LAT_MAX - LAT_MIN) / STEP);

const cells = [];
for (let row = 0; row <= rows; row++) {
  const lat = LAT_MAX - row * STEP;
  for (let col = 0; col <= cols; col++) {
    if (isLand(-180 + col * STEP, lat)) cells.push(`${col},${row}`);
  }
}

// Wrap so the generated source stays readable in a diff.
const lines = [];
let current = "";
for (const cell of cells) {
  if (`${current} ${cell}`.length > 76) {
    lines.push(current);
    current = cell;
  } else {
    current = current ? `${current} ${cell}` : cell;
  }
}
if (current) lines.push(current);

const out = `/**
 * A dotted world map, used as the quiet backdrop of the landing hero.
 *
 * Land is sampled on a ${STEP}° graticule and drawn as one dot per cell, so the
 * continents are literally made of spots — the same mark as the wordmark's
 * \`o\` and the map markers. Antarctica and the high Arctic are cropped: on an
 * equirectangular grid they oversample into solid bars rather than reading as
 * land.
 *
 * Geometry derived from Natural Earth 110m land (public domain).
 * Generated by scripts/generate-world-map.mjs — edit the generator, not this.
 */

/** Grid extent in cells; the SVG viewBox is \`0 0 MAP_COLS MAP_ROWS\`. */
export const MAP_COLS = ${cols};
export const MAP_ROWS = ${rows};

/** Land cells as \`col,row\` pairs, whitespace separated. */
export const MAP_CELLS = \`
${lines.join("\n")}
\`;
`;

const target = path.join(
  import.meta.dirname,
  "..",
  "src",
  "components",
  "world-map-data.ts",
);
fs.writeFileSync(target, out);
console.error(`${cells.length} cells across ${cols}x${rows} → ${target}`);
